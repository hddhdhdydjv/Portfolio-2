// Regenerates prismicio-types.d.ts from the local models (Slice Machine does this too).
import fs from 'node:fs'
import path from 'node:path'
import { generateTypes } from 'prismic-ts-codegen'
import { ROOT } from './lib/build-content.mjs'

const read = (p) => JSON.parse(fs.readFileSync(p, 'utf8'))
const customTypeModels = fs.readdirSync(path.join(ROOT, 'customtypes')).map((d) => read(path.join(ROOT, 'customtypes', d, 'index.json')))
const sliceDir = path.join(ROOT, 'app/slices')
const sharedSliceModels = fs.readdirSync(sliceDir).filter((d) => fs.existsSync(path.join(sliceDir, d, 'model.json'))).map((d) => read(path.join(sliceDir, d, 'model.json')))
const types = generateTypes({ customTypeModels, sharedSliceModels, typesProvider: '@prismicio/client', clientIntegration: { includeCreateClientInterface: true, includeContentNamespace: true } })
fs.writeFileSync(path.join(ROOT, 'prismicio-types.d.ts'), `// Code generated by Slice Machine. DO NOT EDIT.\n\n${types}`)
console.log('prismicio-types.d.ts updated')
